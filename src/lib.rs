//! emmu-nds — Nintendo DS core for Emmu.
//!
//! Wraps `dust-core` (vendored from `Kelpsyberry/dust`, GPL-3.0) behind a
//! WASM-friendly facade compatible with Emmu's worker protocol.
//!
//! Frame contract: one stacked RGBA8888 image, 256x384 (top screen above
//! bottom screen). Save states use the magic `EMMUNDS1`, a u32 version and the
//! savestate blob produced by `dust-core`.

mod renderer_3d;
mod wasm;

pub use wasm::*;

/// Width of each Nintendo DS LCD, in pixels.
pub const SCREEN_WIDTH: usize = 256;
/// Height of each Nintendo DS LCD, in pixels.
pub const SCREEN_HEIGHT: usize = 192;
/// Height of the stacked frame sent to the UI (two screens).
pub const FRAME_HEIGHT: usize = SCREEN_HEIGHT * 2;
/// Save state magic/version, e.g. `EMMUNDS1`.
pub const SAVE_MAGIC: &[u8; 8] = b"EMMUNDS1";
/// Core save state format version. Bump whenever the core changes its layout.
pub const SAVE_VERSION: u32 = 1;
/// Audio sample rate generated by the DS core.
///
/// Without the `xq-audio` feature, `dust-core` emits one sample every 1024
/// cycles of the 33.554432 MHz ARM7 clock (33_554_432 / 1024 = 32768 Hz).
/// Announcing 44100 here makes the worklet consume the queue ~35% faster than
/// the core fills it, causing pitch shifts and constant underruns.
pub const AUDIO_SAMPLE_RATE: u32 = 32_768;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn frame_is_stacked_256x384() {
        assert_eq!(SCREEN_WIDTH, 256);
        assert_eq!(SCREEN_HEIGHT, 192);
        assert_eq!(FRAME_HEIGHT, 384);
        assert_eq!(SCREEN_WIDTH * FRAME_HEIGHT * 4, 256 * 384 * 4);
    }

    #[test]
    fn save_magic_is_stable() {
        assert_eq!(SAVE_MAGIC, b"EMMUNDS1");
    }

    #[test]
    fn audio_rate_matches_dust_output() {
        // dust-core generates one sample every 1024 cycles of the 33.554432 MHz
        // ARM7 clock unless the optional `xq-audio` feature is enabled.
        assert_eq!(AUDIO_SAMPLE_RATE, 33_554_432 / 1024);
    }
}
